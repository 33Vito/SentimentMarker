#!/usr/bin/env node
/* Rebuild the six-edition, file://-friendly data pack with the canonical Finance engine. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const C = require('../sentiment-core.js');
const { detail } = require('./score-cli.js');
new Function('SMCore', fs.readFileSync(path.join(root, C.lexiconSrc('finance')), 'utf8'))(C);
const sourceContext = { window: {} };
require('node:vm').runInNewContext(fs.readFileSync(path.join(root, 'examples/fsr-evolution-assessments.js'), 'utf8'), sourceContext);

const clean = s => s.replace(/\u00ad/g, '').replace(/\s+/g, ' ').replace(/(^|[.:;]\s+)y (?=[A-Z])/g, '$1• ')
  .replace(/and\/ or/g, 'and/or').trim();
function historicalBlocks(blocks) {
  // Page boundaries can bisect sentences. Keep substantive headings, which the
  // historical text layer already includes inline with the narrative.
  const text = clean(blocks.map(b => b.text).join(' '))
    .replace(/\s+Endnotes?\s[\s\S]*$/, '')
    .replace(/This Financial Stability Review was finalised on [^.]+\.\s*/g, '');
  return [{ type: 'p', text }];
}

function currentBlocks(raw) {
  const text = raw.replace(/\r\n?/g, '\n');
  const boundary = '\n\n## Box: Key global and domestic vulnerabilities';
  if (!text.includes(boundary)) throw Error('October Assessment scope boundary changed');
  const blocks = C.parseMarkdown(text.split(boundary)[0]);
  // The industry callout interrupts this sentence in PDF reading order. Move
  // only its verified continuation, preserving the callout as its own prose.
  const start = blocks.find(b => b.text.endsWith('a growing focus of'));
  const continuation = 'financial system regulators in Australia and internationally.';
  const end = blocks.find(b => b.text.startsWith(continuation));
  if (!start || !end) throw Error('October split-sentence anchors changed');
  start.text += ' ' + continuation;
  end.text = end.text.slice(continuation.length).trim();
  const labels = new Set(['Financial Stability Assessment', 'Overall assessment', 'Key messages for industry']);
  return blocks.filter(b => !labels.has(b.text) && b.text)
    .map(b => ({ type: 'p', text: clean(b.text) }));
}

function buildEditions() {
  const sources = Object.entries(sourceContext.window.SM_EVOLUTION_SOURCE).map(([date, v]) => ({
    date, title: v.title, sourcePdfPages: v.sourcePdfPages, source: `https://www.rba.gov.au/publications/fsr/${date.slice(0,4)}/${date.slice(5) === '03' ? 'mar' : date.slice(5) === '04' ? 'apr' : date.slice(5) === '09' ? 'sep' : 'oct'}/`,
    blocks: historicalBlocks(v.blocks),
    quality: date === '2025-04' || date === '2025-10' ? 'Original heading ellipses retained; standalone punctuation and endnotes excluded from counts.' : 'Page breaks and bullet glyphs normalised; publication metadata excluded.'
  }));
  const current = fs.readFileSync(path.join(root, 'examples/fsr-assessment-2026-10.txt'), 'utf8');
  sources.push({ date: '2026-10', title: 'RBA Financial Stability Review · 2026-10 (Assessment)', sourcePdfPages: [4,12],
    source: 'https://www.rba.gov.au/publications/fsr/2026/oct/',
    blocks: currentBlocks(current),
    quality: 'Substantive headings included; interrupted sentence restored. Closing Box, Figure 1 and Endnotes excluded.' });

  const editions = sources.map(src => {
    const doc = C.buildDoc(src.title, src.blocks, { profile: 'finance' });
    const sentences = doc.sents.filter(s => /[\p{L}\p{N}]/u.test(s.text)).map(s => ({ text: s.text, score: s.score,
      words: detail(C, C.analyzeSentence(s.text, 'finance')).words }));
    return { date: src.date, title: src.title, source: src.source, sourcePdfPages: src.sourcePdfPages,
      scope: 'Financial Stability Assessment narrative including substantive headings', quality: src.quality,
      model: doc.model, sentences };
  });
  return editions;
}

function main() {
  const editions = buildEditions();
  const out = '/* Generated by node tools/build-evolution.js; Finance model ' + C.modelVersion + '. */\nwindow.SM_EVOLUTION = ' + JSON.stringify(editions) + ';\n';
  const dest = path.join(root, 'examples/fsr-evolution.scored.js');
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== out) throw Error('Evolution pack is stale; run node tools/build-evolution.js');
    console.log('Evolution pack current:', editions.map(e => `${e.date} ${e.sentences.length}`).join(', '));
  } else {
    fs.writeFileSync(dest, out);
    console.log('Wrote', dest, editions.map(e => `${e.date} ${e.sentences.length}`).join(', '));
  }
}
if (require.main === module) main();
module.exports = { historicalBlocks, currentBlocks, buildEditions };
